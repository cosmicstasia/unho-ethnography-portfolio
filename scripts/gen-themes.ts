// Generates src/styles/themes.css and src/data/themes.json from the Omarchy
// theme palettes installed on this machine.
//
//   bun scripts/gen-themes.ts [/usr/share/omarchy/themes]
//
// Every text color is checked against the theme's backgrounds and pulled toward
// the foreground until it clears WCAG AA (4.5:1) with a small margin, so all themes stay readable.

import { readdirSync, existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2] ?? '/usr/share/omarchy/themes';

type RGB = [number, number, number];
const hex = (h: string): RGB => {
  const s = h.replace('#', '');
  return [0, 2, 4].map((i) => parseInt(s.slice(i, i + 2), 16)) as RGB;
};
const toHex = (c: RGB) => '#' + c.map((v) => Math.round(v).toString(16).padStart(2, '0')).join('');
const mix = (a: RGB, b: RGB, t: number): RGB => a.map((v, i) => v + (b[i] - v) * t) as RGB;
const lum = (c: RGB) => {
  const [r, g, b] = c.map((v) => {
    const x = v / 255;
    return x <= 0.03928 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const contrast = (a: RGB, b: RGB) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};

// Move `c` toward `toward` until it clears `min` against every background.
// The check runs on the rounded hex value, with a small margin over AA's 4.5:1.
const readable = (c: RGB, bgs: RGB[], toward: RGB, min = 4.6): RGB => {
  for (let t = 0; t <= 1; t += 0.02) {
    const m = hex(toHex(mix(c, toward, t)));
    if (bgs.every((b) => contrast(m, b) >= min)) return m;
  }
  return toward;
};

const nameOf = (slug: string) =>
  slug
    .split('-')
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join(' ');

const themes: { id: string; name: string; mode: 'dark' | 'light'; swatches: string[] }[] = [];
let css = '/* Generated by scripts/gen-themes.ts from Omarchy theme palettes. Do not edit by hand. */\n';

for (const slug of readdirSync(dir).sort()) {
  const file = join(dir, slug, 'colors.toml');
  if (!existsSync(file)) continue;
  const p = (await import(file)).default as Record<string, string>;

  const bg = hex(p.background);
  const fg = hex(p.foreground);
  const light = (p.mode ?? (lum(bg) > 0.5 ? 'light' : 'dark')) === 'light';
  const white: RGB = [255, 255, 255];

  const sunken = hex(p.dark_background ?? toHex(mix(bg, fg, 0.04)));
  const deep = hex(p.darker_background ?? toHex(mix(bg, fg, 0.08)));
  const raised = hex(toHex(light ? mix(bg, white, 0.65) : mix(bg, fg, 0.05)));
  const surfaces = [bg, sunken, raised];

  const pick = (...keys: string[]) => hex(keys.map((k) => p[k]).find(Boolean) ?? p.accent);
  const strong = readable(hex(p.bright_foreground ?? p.foreground), surfaces, fg, 7);
  const text = readable(fg, surfaces, strong, 7);
  const tone = (c: RGB) => readable(c, surfaces, text);

  const vars: Record<string, RGB> = {
    bg,
    sunken,
    deep,
    raised,
    line: mix(bg, fg, 0.14),
    'line-strong': mix(bg, fg, 0.26),
    fg: text,
    strong,
    soft: readable(mix(text, bg, 0.18), surfaces, text),
    muted: readable(mix(text, bg, 0.34), surfaces, text),
    accent: tone(pick('accent')),
    blue: tone(pick('blue')),
    cyan: tone(pick('cyan', 'blue')),
    green: tone(pick('green')),
    yellow: tone(pick('yellow')),
    orange: tone(pick('orange', 'bright_yellow', 'red')),
    red: tone(pick('red')),
    magenta: tone(pick('magenta', 'bright_magenta')),
    selection: hex(p.selection ?? toHex(mix(bg, hex(p.accent), 0.3))),
  };

  css += `\n[data-theme='${slug}'] {\n  color-scheme: ${light ? 'light' : 'dark'};\n`;
  for (const [k, v] of Object.entries(vars)) css += `  --c-${k}: ${toHex(v)};\n`;
  css += '}\n';

  themes.push({
    id: slug,
    name: nameOf(slug),
    mode: light ? 'light' : 'dark',
    swatches: [vars.bg, vars.accent, vars.orange, vars.green, vars.magenta].map(toHex),
  });
}

writeFileSync('src/styles/themes.css', css);
writeFileSync('src/data/themes.json', JSON.stringify(themes, null, 2) + '\n');
console.log(`wrote ${themes.length} themes`);
